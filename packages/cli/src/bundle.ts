// The per-Mac integration bundle: one directory every agent client is wired to.
//
//   ~/.apple-cua/bundle/
//     bundle.json                          stamp: version, content hash, the checkout that generated it
//     .claude-plugin/marketplace.json      Claude Code local marketplace
//     .agents/plugins/marketplace.json     Codex local marketplace
//     plugins/apple-cua/
//       .claude-plugin/plugin.json         Claude Code plugin manifest
//       .codex-plugin/plugin.json          Codex plugin manifest
//       .mcp.json                          the signed helper, server.js and the saved settings as env
//       gemini-extension.json              Gemini CLI extension manifest (the same server)
//       skills/apple-cua/                  the skill, copied from the checkout
//
// Clients that copy plugins into a cache (Claude Code, Codex) decide whether to update by the version, so the version
// carries a hash of everything else in the bundle: the same content always has the same version, which makes setup
// idempotent, and any change (settings, skill text, a new checkout path) produces a new one.

import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, readdirSync, renameSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import type { LaunchCommand } from "./clients.js";

export const PLUGIN_NAME = "apple-cua";
export const MARKETPLACE_NAME = "apple-cua-local";
export const MCP_SERVER_NAME = "apple-cua";
export const PLUGIN_DIRECTORY = `plugins/${PLUGIN_NAME}`;
export const SKILL_DIRECTORY = `${PLUGIN_DIRECTORY}/skills/apple-cua`;
const STAMP_FILE = "bundle.json";
const HOMEPAGE = "https://github.com/trac3r00/apple-cua";
const DESCRIPTION =
	"Operate macOS apps you approve, and an iPhone through iPhone Mirroring, through the signed apple-cua-mcp helper: observe, act, verify, and stop when unsure.";

export interface BundleFile {
	/** Relative to the bundle root, with forward slashes. */
	readonly path: string;
	readonly content: string;
}

export interface BundleInputs {
	readonly checkout: string;
	/** apple-cua's own version (packages/mcp/package.json); the content hash is appended to it. */
	readonly baseVersion: string;
	readonly launch: LaunchCommand;
	/** The saved settings as the server's environment; only keys with a value. */
	readonly env: Readonly<Record<string, string>>;
	/** The skill's files, paths relative to skills/apple-cua. */
	readonly skill: readonly BundleFile[];
}

export interface BundlePlan {
	/** `<baseVersion>+codex.<hash>`: Codex requires that cachebuster form, and Claude Code accepts it. */
	readonly version: string;
	readonly hash: string;
	readonly checkout: string;
	readonly files: readonly BundleFile[];
}

export interface BundleStamp {
	readonly version: string;
	readonly hash: string;
	readonly checkout: string;
}

function json(value: unknown): string {
	return `${JSON.stringify(value, null, 2)}\n`;
}

